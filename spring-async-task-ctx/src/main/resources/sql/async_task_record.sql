-- MySQL
CREATE TABLE async_task_record (
    TASK_ID       VARCHAR(64)  NOT NULL COMMENT '任务ID',
    SERVICE       VARCHAR(64)  NOT NULL COMMENT '归属服务名，服务级隔离',
    BUSINESS_CODE VARCHAR(64)  NOT NULL COMMENT '业务编码，路由键与过滤维度',
    TAG           VARCHAR(128) COMMENT '过滤标签',
    PAYLOAD       LONGTEXT COMMENT '业务参数JSON',
    STATUS        VARCHAR(16)  NOT NULL COMMENT '状态 PENDING/RUNNING/SUCCESS/FAILED/EXPIRED',
    RETRY_COUNT   INT          NOT NULL DEFAULT 0 COMMENT '重试次数',
    NEXT_RUN_TIME DATETIME COMMENT '下次执行时间',
    LOCK_OWNER    VARCHAR(128) COMMENT '集群抢占标识',
    RESULT        LONGTEXT COMMENT '任务结果JSON',
    ERROR_MSG     LONGTEXT COMMENT '错误信息',
    CREATE_PERSON BIGINT COMMENT '创建人',
    UPDATE_PERSON BIGINT COMMENT '更新人',
    CREATE_TIME   DATETIME COMMENT '创建时间',
    UPDATE_TIME   DATETIME COMMENT '更新时间',
    PRIMARY KEY (TASK_ID),
    KEY IDX_ASYNC_TASK_SERVICE (SERVICE, STATUS, NEXT_RUN_TIME),
    KEY IDX_ASYNC_TASK_CODE (SERVICE, BUSINESS_CODE),
    KEY IDX_ASYNC_TASK_TAG (TAG)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COMMENT = '异步任务记录';
